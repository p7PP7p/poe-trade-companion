  function pick(dict, dictLower, core) {
    if (!dict) return null;
    var v = dict[core];
    if (typeof v === 'string' && v) return v;
    if (dictLower) {
      var lv = dictLower[core.toLowerCase()];
      if (typeof lv === 'string' && lv) return lv;
    }
    return null;
  }

  /** 单条模板应用：参数先用词条翻译，再按 allowEnglish 做残留英文校验 */
  function applyPattern(p, core, dict, dictLower) {
    if (!p || !p.re) return null;
    var m = p.re.exec(core);
    if (!m) return null;
    var out = p.tpl.replace(/\$(\d+)/g, function (_, n) {
      var v = m[Number(n)];
      if (v === undefined || v === null) return '';
      var hit = pick(dict, dictLower, v);
      return hit === null ? v : hit;
    });
    if (out === core) return null;
    if (!p.allowEnglish && /[A-Za-z]{2,}/.test(out)) return null;
    return out;
  }

  /**
   * 文本匹配：精确 → 句式模板 → null（调用方保留英文原样）
   * @param {string} core 已归一化（压缩空白、去首尾空格）的英文文本
   */
  /* ------------------------------------------------ 分词兜底匹配（v0.3.2 新增）
   *
   * 用途：官方市集大量下拉项是「已知词条 + 已知词条」拼出来的（One-Handed melee Weapon、
   * Any Dagger、Claws (Claw)、Damage / 100%），逐条登记组合会无限膨胀。
   * 纪律：所有英文单词都必须能在词库中命中，任一单词未命中即整体放弃（保留英文原样），
   * 因而绝不会产出半中半英；纯数字与标点按全角规则原样保留。
   */
  var SEG_SPLIT = /([A-Za-z][A-Za-z'\u2019\-]*)/;

  function mapSep(sep) {
    var t = String(sep || '').replace(/[\s\u00a0]+/g, ' ').trim();
    if (!t) return '';
    var out = '';
    for (var i = 0; i < t.length; i += 1) {
      var c = t.charAt(i);
      if (c === '(') out += '（';
      else if (c === ')') out += '）';
      else if (c === ':') out += '：';
      else if (c === ',') out += '，';
      else if (c === ';') out += '；';
      else if (c === '!') out += '！';
      else if (c === '?') out += '？';
      else out += c;
    }
    /* 数字 / 百分号 / 斜杠前面补一个空格，避免「伤害/ 100%」粘连 */
    if (/^[\/\d%+\-]/.test(t)) out = ' ' + out;
    return out;
  }

  function segmentMatch(core, dict, dictLower) {
    if (!core || core.length > 64) return null;
    var parts = core.split(SEG_SPLIT);
    var words = [];
    var seps = [];
    var buf = '';
    for (var i = 0; i < parts.length; i += 1) {
      var seg = parts[i];
      if (seg === '') continue;
      if (i % 2 === 0) {
        buf += seg;
      } else {
        seps.push(buf);
        buf = '';
        words.push(seg);
      }
    }
    seps.push(buf);
    if (!words.length || words.length > 8) return null;
    if (seps.length !== words.length + 1) return null;

    /* 贪心最长匹配：从当前位置起尝试 5..1 个单词组成的短语 */
    var picks = [];
    var idx = 0;
    while (idx < words.length) {
      var hit = null;
      var used = 0;
      for (var len = Math.min(5, words.length - idx); len >= 1; len -= 1) {
        var phrase = words.slice(idx, idx + len).join(' ');
        var v = pick(dict, dictLower, phrase);
        if (v === null) v = pick(dict, dictLower, phrase + (len === 1 ? '' : 's'));
        if (v !== null) {
          hit = v;
          used = len;
          break;
        }
      }
      if (hit === null) return null;   // 有单词未命中：整体放弃，不出半中半英
      picks.push(hit);
      idx += used;
    }
    if (picks.length !== words.length) return null;

    var out = '';
    for (var w = 0; w < words.length; w += 1) {
      out += mapSep(seps[w]);
      out += picks[w];
    }
    out += mapSep(seps[words.length]);
    if (!out || out === core) return null;
    if (/[A-Za-z]{2,}/.test(out)) return null;
    return out;
  }

  function matchText(core, dict, dictLower, patterns, patternsEnabled) {
    if (!core) return null;
    var hit = pick(dict, dictLower, core);
    if (hit !== null) return hit;
    if (patternsEnabled === false || !Array.isArray(patterns)) return null;
    for (var i = 0; i < patterns.length; i++) {
      var out = applyPattern(patterns[i], core, dict, dictLower);
      if (out !== null) return out;
    }
    /* 最后一层：分词组合兜底（全部单词命中才输出） */
    return segmentMatch(core, dict, dictLower);
  }

